import { existsSync } from 'node:fs'
import { NextRequest, NextResponse } from 'next/server'
import chromium from '@sparticuz/chromium'
import puppeteer from 'puppeteer-core'
import JSZip from 'jszip'
import { createClient } from '@/lib/supabase/server'
import type { ResumeData, ResumeLioTemplateId, ResumeLioSocialLinks } from '@/types'

export const runtime = 'nodejs'
export const maxDuration = 60

interface ZipRequestPayload {
  slug: string
  data: ResumeData
  templateId: ResumeLioTemplateId
  socialLinks?: ResumeLioSocialLinks
  imageOverrides?: Record<string, string>
}

function getRequestOrigin(request: NextRequest) {
  const host = request.headers.get('x-forwarded-host') ?? request.headers.get('host')
  const protocol = request.headers.get('x-forwarded-proto') ?? 'http'
  if (!host) return process.env.NEXT_PUBLIC_APP_URL ?? 'http://localhost:3000'
  return `${protocol}://${host}`
}

function findLocalChromeExecutable() {
  const candidates = [
    process.env.CHROME_EXECUTABLE_PATH,
    '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
    '/Applications/Chromium.app/Contents/MacOS/Chromium',
    '/usr/bin/google-chrome-stable',
    '/usr/bin/google-chrome',
    '/usr/bin/chromium-browser',
    '/usr/bin/chromium',
  ].filter((c): c is string => Boolean(c))
  return candidates.find(c => existsSync(c)) ?? null
}

async function getExecutablePath() {
  const local = findLocalChromeExecutable()
  return local ?? chromium.executablePath()
}

function buildHtmlDocument(opts: {
  name: string
  bodyHTML: string
  inlineCSS: string
  fontLinks: string[]
}): string {
  const { name, bodyHTML, inlineCSS, fontLinks } = opts
  const fontLinkTags = fontLinks
    .map(href => `  <link rel="stylesheet" href="${href}">`)
    .join('\n')

  return `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${name}</title>
  <meta name="description" content="Personal website of ${name}">
${fontLinkTags}
  <style>
    *, *::before, *::after { box-sizing: border-box; }
    body { margin: 0; padding: 0; }
    /* Ensure animations are visible in static export */
    #zip-render-root [style*="opacity: 0"] { opacity: 1 !important; }
    #zip-render-root [style*="opacity:0"] { opacity: 1 !important; }
${inlineCSS}
  </style>
</head>
<body>
${bodyHTML}
</body>
</html>`
}

