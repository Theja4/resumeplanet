const VERCEL_JSON = JSON.stringify({ cleanUrls: true, trailingSlash: false }, null, 2)

const NETLIFY_TOML = `[build]
  publish = "."
`

export async function POST(request: NextRequest) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()
  if (!user) return NextResponse.json({ error: 'Unauthorized' }, { status: 401 })

  let payload: ZipRequestPayload
  try {
    payload = await request.json()
  } catch {
    return NextResponse.json({ error: 'Invalid request payload.' }, { status: 400 })
  }

  if (!payload.data || !payload.slug || !payload.templateId) {
    return NextResponse.json({ error: 'Missing required fields.' }, { status: 400 })
  }

  const origin = getRequestOrigin(request)
  const personName = payload.data.name || 'resume'
  const safeSlug = (payload.slug || 'my-site').replace(/[^\w-]/g, '')
  let browser: Awaited<ReturnType<typeof puppeteer.launch>> | null = null

  try {
    const executablePath = await getExecutablePath()
    const isLocal = Boolean(findLocalChromeExecutable())

    browser = await puppeteer.launch({
      args: isLocal
        ? ['--no-sandbox', '--disable-setuid-sandbox']
        : [...chromium.args, '--no-sandbox', '--disable-setuid-sandbox'],
      defaultViewport: { width: 1440, height: 900, deviceScaleFactor: 1 },
      executablePath,
      headless: true,
    })

    const page = await browser.newPage()
    await page.goto(`${origin}/resume-lio/zip-render`, { waitUntil: 'networkidle0' })

    // Speed up all CSS animations/transitions so elements are in their final state
    await page.addStyleTag({
      content: `*, *::before, *::after {
        animation-duration: 0.001ms !important;
        animation-delay: 0ms !important;
        transition-duration: 0.001ms !important;
        transition-delay: 0ms !important;
      }`,
    })

    await page.evaluate((p) => {
      window.__REZOOMED_ZIP_PAYLOAD__ = p
      window.dispatchEvent(new CustomEvent('rezoomed:zip-payload', { detail: p }))
    }, {
      data: payload.data,
      templateId: payload.templateId,
      socialLinks: payload.socialLinks ?? {},
      imageOverrides: payload.imageOverrides ?? {},
    })

    await page.waitForFunction(
      () => document.documentElement.dataset.rezoomedZipReady === '1',
      { timeout: 15000 }
    )

    // Short pause to let any remaining paint settle
    await new Promise(r => setTimeout(r, 400))

    // Extract rendered HTML and all CSS from the page
    const extracted = await page.evaluate(async () => {
      const fontLinks: string[] = []
      const cssChunks: string[] = []

      for (const el of Array.from(document.querySelectorAll('link[rel="stylesheet"]'))) {
        const link = el as HTMLLinkElement
        if (link.href.includes('fonts.googleapis.com') || link.href.includes('fonts.gstatic.com')) {
          fontLinks.push(link.href)
          continue
        }
        try {
          const res = await fetch(link.href)
          if (res.ok) cssChunks.push(await res.text())
        } catch { /* skip inaccessible sheets */ }
      }

      for (const el of Array.from(document.querySelectorAll('style'))) {
        const text = (el as HTMLStyleElement).textContent?.trim()
        if (text) cssChunks.push(text)
      }

      // Reset any Framer Motion initial opacity states before capturing
      const root = document.getElementById('zip-render-root')
      if (root) {
        root.querySelectorAll<HTMLElement>('[style]').forEach(el => {
          if (el.style.opacity === '0') el.style.opacity = '1'
          if (el.style.visibility === 'hidden') el.style.visibility = 'visible'
        })
      }

      return {
        bodyHTML: root ? root.outerHTML : document.body.innerHTML,
        inlineCSS: cssChunks.join('\n'),
        fontLinks,
      }
    })

    const finalHTML = buildHtmlDocument({
      name: personName,
      bodyHTML: extracted.bodyHTML,
      inlineCSS: extracted.inlineCSS,
      fontLinks: extracted.fontLinks,
    })

    const zip = new JSZip()
    zip.file('index.html', finalHTML)
    zip.file('vercel.json', VERCEL_JSON)
    zip.file('netlify.toml', NETLIFY_TOML)
    zip.file('README.md', README)

    const zipBuffer = await zip.generateAsync({
      type: 'nodebuffer',
      compression: 'DEFLATE',
      compressionOptions: { level: 6 },
    })

    return new NextResponse(zipBuffer, {
      headers: {
        'Content-Type': 'application/zip',
        'Content-Disposition': `attachment; filename="${safeSlug}-site.zip"`,
        'Cache-Control': 'no-store',
      },
    })
  } catch (error) {
    console.error('ZIP export failed.', error)
    return NextResponse.json(
      { error: error instanceof Error ? error.message : 'ZIP export failed.' },
      { status: 500 }
    )
  } finally {
    await browser?.close()
  }
}
